    @Override
    public void setupAnim(StarPlatinumRenderState state) {
        super.setupAnim(state);
        resetPose();
        headClip = null;

        // Base layer: looping idle (keyframes from the original animation json).
        applyClip(TheWorldAnimData.IDLE, TheWorldAnimData.IDLE.wrap(state.ageInTicks / 20.0F));

        // Action layer overrides the bones it keys, the rest keep their idle pose.
        // Phases 1..3 are the punches (heavyAttack picks light/heavy; abilityKind=1 selects kick,
        // abilityKind=2 selects the time-breaker heavy punch).
        // Phase 4 barrage, 5 guard, 6 guard broken, 10 time stop charge. Anything else stays idle.
        switch (state.actionPhase) {
            case StarPlatinumRenderState.PHASE_WINDUP, StarPlatinumRenderState.PHASE_PERFORM,
                 StarPlatinumRenderState.PHASE_RECOVERY -> applyPunch(state);
            case StarPlatinumRenderState.PHASE_BARRAGE -> applyBarrage(state);
            case StarPlatinumRenderState.PHASE_GUARD -> applyGuard(state);
            case StarPlatinumRenderState.PHASE_GUARD_BROKEN -> applyGuardBroken(state);
            case StarPlatinumRenderState.PHASE_TIME_STOP -> applyTimeStop(state);
            default -> { }
        }

        // The json's head channel is a MoLang query (query.head_x/y_rotation): replaced by the render state's look angles.
        ModelPart head = bones.get("head");
        var channels = headClip == null ? null : TheWorldAnimData.HEAD.get(headClip.name());
        if (channels == null) {
            head.xRot += state.xRot * ((float) Math.PI / 180F);
            head.yRot += state.yRot * ((float) Math.PI / 180F);
        } else {
            channels[0].sample(headTime, headSample);
            for (int i = 1; i < 3; i++) {
                channels[i].sample(headTime, sample);
                float angle = i == 1 ? state.xRot : state.yRot;
                for (int axis = 0; axis < 3; axis++) headSample[axis] += sample[axis] * angle;
            }
            var initial = head.getInitialPose();
            head.xRot = initial.xRot() + (float) Math.toRadians(headSample[0]);
            head.yRot = initial.yRot() + (float) Math.toRadians(headSample[1]);
            head.zRot = initial.zRot() + (float) Math.toRadians(headSample[2]);
        }
    }

    private void applyPunch(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip;
        if (state.abilityKind == ABILITY_KICK) {
            clip = TheWorldAnimData.KICK;
        } else if (state.abilityKind == ABILITY_TS_HEAVY_PUNCH) {
            clip = TheWorldAnimData.TIME_BREAKER;
        } else {
            clip = state.heavyAttack ? TheWorldAnimData.HEAVY_PUNCH : TheWorldAnimData.LIGHT_PUNCH;
        }
        int phase = Math.max(1, Math.min(3, state.actionPhase)) - 1;
        float start = clip.phaseStarts()[phase];
        float end = phase < 2 ? clip.phaseStarts()[phase + 1] : clip.length();
        float progress = state.actionDuration > 0 ? Math.clamp(state.actionTicks / state.actionDuration, 0, 1) : 0;
        float time = start + (end - start) * progress;
        applyClip(clip, clip.wrap(time));
    }

    /**
     * The original "timeStop" animation: charge/windup phase plays over [0.0, 1.0] seconds (duration 20 ticks).
     */
    private void applyTimeStop(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = TheWorldAnimData.TIME_STOP;
        float windupEnd = clip.phaseStarts()[1];
        float progress = state.actionDuration > 0 ? Math.clamp(state.actionTicks / state.actionDuration, 0, 1) : 0;
        float time = windupEnd * progress;
        applyClip(clip, clip.wrap(time));
    }

    /**
     * The original "barrage" animation ({@code phase.loopBack = 0}): its PERFORM phase loops over [0, RECOVERY start)
     * in animation seconds, independent of the phase duration. The loop is seamless because every keyed bone has the
     * same value at 0 and at the loop end.
     */
    private void applyBarrage(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = TheWorldAnimData.BARRAGE;
        float seconds = Math.max(0, state.actionTicks) / 20.0F * ANIM_SPEED;
        float time = clip.wrapLoopBack(seconds);
        applyClip(clip, time);
        applyLookBindings(clip, time, state);
    }

    /** The original "block" animation: a single static pose (no timeline, no length). */
    private void applyGuard(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = TheWorldAnimData.GUARD;
        applyClip(clip, clip.wrap(0));
        applyLookBindings(clip, 0, state);
    }

    /**
     * NOT an original animation (the original json has no guard-broken pose): the idle pose plus a small procedural
     * stagger of the upper body - a lean backwards with a slight sideways wobble that decays back to idle over the
     * phase. No punch clip is involved.
     */
    private void applyGuardBroken(StarPlatinumRenderState state) {
        float progress = state.actionDuration > 0 ? Math.clamp(state.actionTicks / state.actionDuration, 0, 1) : 0;
        ModelPart upperPart = bones.get("upperPart");
        // Negative X rotation tips the torso backwards (same sign convention as the arms: -90 degrees raises them forward).
        upperPart.xRot -= GUARD_BROKEN_LEAN * (float) Math.sin(progress * Math.PI);
        upperPart.zRot += GUARD_BROKEN_WOBBLE * (float) Math.sin(progress * TWO_PI) * (1 - progress);
    }

    /**
     * Binds the clip's {@link StarPlatinumAnimClip.LookBinding}s (rotation slots that are {@code query.head_x_rotation}
     * / {@code query.head_y_rotation} in the json, both in degrees like the original's MoLang context) to the render
     * state's look angles.
     */
    private void applyLookBindings(StarPlatinumAnimClip.Clip clip, float time, StarPlatinumRenderState state) {
        for (StarPlatinumAnimClip.LookBinding look : clip.looks()) {
            if (time > look.activeUntil()) continue;
            ModelPart part = bones.get(look.bone());
            if (part == null) continue;
            sample[0] = look.constant()[0];
            sample[1] = look.constant()[1];
            sample[2] = look.constant()[2];
            if (look.pitchSlot() >= 0) sample[look.pitchSlot()] = state.xRot;
            if (look.yawSlot() >= 0) sample[look.yawSlot()] = state.yRot;
            PartPose initial = part.getInitialPose();
            part.xRot = initial.xRot() + (float) Math.toRadians(sample[0]);
            part.yRot = initial.yRot() + (float) Math.toRadians(sample[1]);
            part.zRot = initial.zRot() + (float) Math.toRadians(sample[2]);
        }
    }

    private void applyClip(StarPlatinumAnimClip.Clip clip, float time) {
        if (TheWorldAnimData.HEAD.containsKey(clip.name())) { headClip = clip; headTime = time; }
        for (StarPlatinumAnimClip.Channel channel : clip.channels()) {
            ModelPart part = bones.get(channel.bone());
            if (part == null) continue;
            channel.sample(time, sample);
            PartPose initial = part.getInitialPose();
            if (channel.position()) {
                part.x = initial.x() + sample[0];
                // GeckoStandAnimator converts animation Y to Minecraft model coordinates.
                part.y = initial.y() - sample[1];
                part.z = initial.z() + sample[2];
            } else {
                part.xRot = initial.xRot() + (float) Math.toRadians(sample[0]);
                part.yRot = initial.yRot() + (float) Math.toRadians(sample[1]);
                part.zRot = initial.zRot() + (float) Math.toRadians(sample[2]);
            }
        }
    }
