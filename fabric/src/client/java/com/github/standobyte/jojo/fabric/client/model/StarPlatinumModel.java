    private void applyInhale(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = StarPlatinumAnimData.INHALE;
        applyClip(clip, clip.wrap(0));
        applyLookBindings(clip, 0, state);
    }

