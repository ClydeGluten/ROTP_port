    @Override
    public void setupAnim(StarPlatinumRenderState state) {
        super.setupAnim(state);
        resetPose();

        // Base layer: looping idle (keyframes from the original animation json).
        applyClip(StarPlatinumAnimData.IDLE, StarPlatinumAnimData.IDLE.wrap(state.ageInTicks / 20.0F));

        // Action layer overrides the bones it keys, the rest keep their idle pose. Phases 1..3 are the punches
        // (heavyAttack picks the clip, or abilityKind=1 selects uppercut); 4..6 are barrage / guard / guard broken;
        // 7..10 are star finger / inhale / zoom / time stop charge. Anything else stays idle.
        switch (state.actionPhase) {
            case StarPlatinumRenderState.PHASE_WINDUP, StarPlatinumRenderState.PHASE_PERFORM,
                 StarPlatinumRenderState.PHASE_RECOVERY -> applyPunch(state);
            case StarPlatinumRenderState.PHASE_BARRAGE -> applyBarrage(state);
            case StarPlatinumRenderState.PHASE_GUARD -> applyGuard(state);
            case StarPlatinumRenderState.PHASE_GUARD_BROKEN -> applyGuardBroken(state);
            case StarPlatinumRenderState.PHASE_STAR_FINGER -> applyStarFinger(state);
            case StarPlatinumRenderState.PHASE_INHALE -> applyInhale(state);
            case StarPlatinumRenderState.PHASE_ZOOM -> applyZoom(state);
            case StarPlatinumRenderState.PHASE_TIME_STOP -> applyTimeStop(state);
            default -> { }
        }

        // The json's head channel is a MoLang query (query.head_x/y_rotation): replaced by the render state's look angles.
        ModelPart head = bones.get("head");
        head.xRot += state.xRot * ((float) Math.PI / 180F);
        head.yRot += state.yRot * ((float) Math.PI / 180F);

        animateHair(state.ageInTicks);
    }

    private void applyPunch(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = state.abilityKind == StarPlatinumRenderState.ABILITY_UPPERCUT
                ? StarPlatinumAnimData.UPPERCUT
                : (state.heavyAttack ? StarPlatinumAnimData.HEAVY_PUNCH : StarPlatinumAnimData.LIGHT_PUNCH);
        float time;
        int phase = Math.max(1, Math.min(3, state.actionPhase)) - 1;
        float start = clip.phaseStarts()[phase];
        float end = phase < 2 ? clip.phaseStarts()[phase + 1] : clip.length();
        float progress = state.actionDuration > 0 ? Math.clamp(state.actionTicks / state.actionDuration, 0, 1) : 0;
        time = start + (end - start) * progress;
        applyClip(clip, clip.wrap(time));
    }

    /**
     * The original "starFinger" animation: static pointing pose from star_platinum.animation.json.
     * Dynamic finger extension (0..3.6 units over 20 ticks) is provided via
     * {@link StarPlatinumRenderState#getStarFingerReach()} for the extending projectile renderer;
     * the Stand body mesh preserves the original 74 parts and 107 cubes.
     */
    private void applyStarFinger(StarPlatinumRenderState state) {
        StarPlatinumAnimClip.Clip clip = StarPlatinumAnimData.STAR_FINGER;
        applyClip(clip, clip.wrap(0));
        applyLookBindings(clip, 0, state);
    }

